"""Reproduce and verify the temporal audit study offline. Requires Python 3.10+.

From this directory run:
  python3 verify.py      (Linux or macOS)
  py -3 verify.py        (Windows)

All regenerated outputs go into a temporary directory. No services or special
permissions are required. Exit 0 means every check in this entry point passed.
"""

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parent
STUDY = ROOT / "study"
OUTPUTS = ("capsules.jsonl", "predictions.csv", "summary.json", "interventions.json")
EXPECTED_ROOT = "174ca466891bbd35e8c5b208b612d74dddf4984b9e7a31537bf7e02d41447e20"
EXPECTED_FIELD = {"attempted": 25, "texts": 22, "http_429": 3, "keyword_alarms": 1, "year_alarms": 0}
CELLS = ("tp", "fp", "tn", "fn", "review_positive", "review_negative", "covered", "n")
EXPECTED_CELLS = {
    "constructed": {
        "year_rule": (4, 12, 52, 28, 0, 0, 96, 96),
        "dated_matcher": (24, 0, 60, 0, 8, 4, 84, 96),
    },
    "challenge": {
        "year_rule": (1, 2, 6, 7, 0, 0, 16, 16),
        "dated_matcher": (0, 0, 2, 0, 8, 6, 2, 16),
    },
}


def run_python(*args: str) -> str:
    process = subprocess.run(
        [sys.executable, "-B", "-X", "utf8", *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if process.returncode:
        raise ValueError(process.stderr.strip() or process.stdout.strip() or "research script failed")
    return process.stdout


def verify_release() -> None:
    sys.dont_write_bytecode = True
    suite = unittest.defaultTestLoader.discover(str(STUDY), pattern="test_capture.py")
    outcome = unittest.TextTestRunner(verbosity=1).run(suite)
    if not outcome.wasSuccessful() or outcome.testsRun != 7 or outcome.skipped:
        raise ValueError("expected seven passing capture tests")

    with tempfile.TemporaryDirectory(prefix="spe-audit-review-") as tmp:
        generated = Path(tmp)
        run_python("study/reproduce.py", "--out", str(generated))
        for name in OUTPUTS:
            if (generated / name).read_bytes() != (STUDY / "results" / name).read_bytes():
                raise ValueError(f"regenerated bytes differ from released {name}")
        print(f"Byte-identical research outputs: {len(OUTPUTS)}/{len(OUTPUTS)}")
        print(run_python("study/capture.py", str(generated / "capsules.jsonl"),
                         "--expected-root", EXPECTED_ROOT).strip())
        summary = json.loads((generated / "summary.json").read_text(encoding="utf-8"))
        if (summary["record_count"], summary["interventions"], summary["capsules_sha256"]) != (124, 12, EXPECTED_ROOT):
            raise ValueError("unexpected record count, intervention count or capsule file digest")
        for split, methods in EXPECTED_CELLS.items():
            for method, counts in methods.items():
                current = summary["splits"][split][method]
                if tuple(current[cell] for cell in CELLS) != counts:
                    raise ValueError(f"published counts differ for {split}/{method}")
    field = json.loads(run_python("field/recount.py"))
    if field != EXPECTED_FIELD:
        raise ValueError("archived pilot recount differs from the published counts")
    print("Classification rows: 96 constructed, 16 challenge. Source interventions: 12.")
    print("Archived pilot: 25 attempts, 22 texts, 3 HTTP 429 errors, 1 keyword alarm, 0 year alarms.")


if __name__ == "__main__":
    if sys.version_info < (3, 10):
        sys.exit("Use Python 3.10 or newer.")
    try:
        verify_release()
    except (KeyError, OSError, ValueError) as exc:
        sys.exit(f"Verification failed: {exc}")
