"""Verify the SPE Audit 1.1 release offline. Requires Python 3.10+ and edition 1.0 alongside v11."""
import argparse
import hashlib
import hmac
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent
MANIFEST = "SHA256.json"
MANIFEST_SCHEMA = "spe-research-file-digests/1"
HEX = re.compile("[a-f0-9]{64}")
DEMO_PIN = "00599656cf1722ca3451915239b04c6f6d86045acb4636757f82c2891ad8c7c8"
TEST_DIRS = (".", "method", "evidence", "review", "languages", "local_model", "robustness", "desk", "interventions")


def digest(path):
    with path.open("rb") as file:
        result = hashlib.sha256()
        for block in iter(lambda: file.read(65536), b""):
            result.update(block)
        return result.hexdigest()


def parse_object(pairs):
    obj = {}
    for k,v in pairs:
        if k in obj:
            raise ValueError(f"duplicate manifest key {k}")
        obj[k] = v
    return obj


def record_manifest():
    entries = {}
    for path in sorted(ROOT.rglob("*")):
        rel = path.relative_to(ROOT)
        if "__pycache__" in rel.parts or path.suffix == ".pyc" or rel.as_posix() == MANIFEST:
            continue
        if path.is_symlink():
            raise ValueError(f"remove symbolic links from the release tree: {rel}")
        if path.is_file():
            if path.name in ("private.json","commitments.json") or path.suffix in (".sqlite",".key",".pem"):
                raise ValueError(f"remove local private artifacts from the release tree: {rel}")
            entries[rel.as_posix()] = digest(path)
    out = ROOT / MANIFEST
    obj = {"schema":MANIFEST_SCHEMA,"algorithm":"SHA-256","sha256":entries}
    out.write_bytes((json.dumps(obj,ensure_ascii=False,indent=2)+"\n").encode())
    print(f"{len(entries)} files indexed, SHA256.json SHA-256 {digest(out)}")


def verify_manifest(expected):
    path = ROOT / MANIFEST
    actual = digest(path)
    if expected is not None and (not HEX.fullmatch(expected) or not hmac.compare_digest(expected,actual)):
        raise ValueError("external SHA256.json digest mismatch")
    manifest = json.loads(path.read_bytes().decode("utf-8"),object_pairs_hook=parse_object)
    if set(manifest) != {"schema","algorithm","sha256"} or manifest["schema"]!=MANIFEST_SCHEMA or manifest["algorithm"]!="SHA-256":
        raise ValueError("unsupported manifest format")
    entries = manifest["sha256"]
    if type(entries) is not dict or not {"verify_v11.py","README.md","SUPPLEMENT_ES.md","SUPPLEMENT_EN.md","FULL_ES.pdf","FULL_EN.pdf","SUPPLEMENT_ES.pdf","SUPPLEMENT_EN.pdf","deposit/zenodo-deposit-1.1.zip"} <= entries.keys():
        raise ValueError("required edition files absent from manifest")
    for name, expected_digest in entries.items():
        relative = PurePosixPath(name)
        if (not name or relative.is_absolute() or relative.as_posix()!=name or ".." in relative.parts
                or name == MANIFEST or "\\" in name or ":" in name or not isinstance(expected_digest,str)
                or not HEX.fullmatch(expected_digest)):
            raise ValueError(f"invalid manifest entry {name!r}")
        file = ROOT.joinpath(*relative.parts)
        if file.resolve()!=file or digest(file)!=expected_digest:
            raise ValueError(f"changed or redirected research file: {name}")
    print(f"{len(entries)} indexed edition files match SHA-256. Manifest {actual}",flush=True)


def command(args, cwd, label, verbose=False):
    env = os.environ.copy()
    env.update({"PYTHONDONTWRITEBYTECODE":"1","PYTHONUTF8":"1","PYTHONIOENCODING":"utf-8"})
    result = subprocess.run([str(x) for x in args],cwd=cwd,env=env,capture_output=True,
                            text=True,encoding="utf-8",errors="replace")
    if result.returncode:
        raise ValueError(f"{label} failed ({result.returncode})\n{result.stdout}\n{result.stderr}")
    print(f"OK  {label}",flush=True)
    if verbose:
        print((result.stdout+"\n"+result.stderr).strip(),flush=True)


def py(directory, label, *args, verbose=False):
    command([sys.executable,"-B","-X","utf8",*args],directory,label,verbose)


def compare(a, b):
    if digest(a)!=digest(b):
        raise ValueError(f"regenerated bytes disagree with {b.relative_to(ROOT)}")


def replay_site(temp):
    # This builder writes next to its inputs. Rebuild in an isolated layout and compare the results.
    research = temp/"site-rebuild"
    edition = research/"v11"
    shutil.copytree(ROOT.parent/"study",research/"study",ignore=shutil.ignore_patterns("__pycache__"))
    for name in ("explore","holdout","reader","results"):
        shutil.copytree(ROOT/name,edition/name,ignore=shutil.ignore_patterns("__pycache__"))
    (research/"assets").mkdir()
    shutil.copyfile(ROOT.parent/"assets/logo.png",research/"assets/logo.png")
    for name in ("data.js","cases.csv","logo.png"):
        (edition/"explore/site"/name).unlink()
    (edition/"explore/offline.zip").unlink()
    py(edition/"explore","static explorer dataset, CSV and offline ZIP rebuilt","build.py")
    for name in ("data.js","cases.csv","logo.png"):
        # The JS writer is text-mode on Windows. Integrity checks above pin the released bytes.
        rebuilt = edition/"explore/site"/name
        released = ROOT/"explore/site"/name
        if name=="data.js" and os.name=="nt":
            if rebuilt.read_text(encoding="utf-8")!=released.read_text(encoding="utf-8"):
                raise ValueError("regenerated explorer data differs")
        else:
            compare(rebuilt,released)
    # Archive members are portable across compression-library versions. Check exact released members
    # against the site; individually compare newly rebuilt members, including normalized JS on Windows.
    release_site=ROOT/"explore/site"
    with zipfile.ZipFile(ROOT/"explore/offline.zip") as original, zipfile.ZipFile(edition/"explore/offline.zip") as rebuilt:
        paths=sorted("spe-audit-explore/"+p.name for p in release_site.iterdir() if p.is_file())
        if sorted(original.namelist())!=paths or sorted(rebuilt.namelist())!=paths:
            raise ValueError("offline package member list mismatch")
        for name in paths:
            canonical=(release_site/PurePosixPath(name).name).read_bytes()
            regenerated=rebuilt.read(name)
            if os.name=="nt" and name.endswith("/data.js"):
                regenerated=regenerated.replace(b"\r\n",b"\n")
            if original.read(name)!=canonical or regenerated!=canonical:
                raise ValueError(f"offline package member mismatch: {name}")


def verify_freezes():
    for name in ("method/freeze.sha256","local_model/freeze.sha256","languages/learned_freeze.sha256"):
        path=ROOT/name
        for line in path.read_text(encoding="utf-8").splitlines():
            checksum,filename=line.split(maxsplit=1)
            if digest(path.parent/filename)!=checksum:
                raise ValueError(f"method freeze mismatch in {name}: {filename}")
    review=json.loads((ROOT/"review/study_freeze.json").read_text(encoding="utf-8"))
    for name,checksum in review["sha256"].items():
        if digest(ROOT/name)!=checksum:
            raise ValueError(f"review packet freeze mismatch for {name}")
    print("OK  published method, learned-model and review freeze files",flush=True)


def verify_study(retrain):
    verify_freezes()
    py(ROOT/"deposit","paper ZIP authorship, DOI, rights and matching integrated PDFs","verify.py","--edition-dir",ROOT)
    py(ROOT.parent,"edition 1.0 tests, 124 captured records and 25 archived attempts","verify.py",verbose=True)
    for directory in TEST_DIRS:
        py(ROOT/directory,f"unit tests in {directory}","-m","unittest","discover","-s",".","-p","test_*.py",verbose=True)
    py(ROOT/"method","threshold calibration","calibrate.py")
    py(ROOT/"method","development-set replay","development_replay.py")
    py(ROOT/"languages","four-language replay and counts","replay_languages.py")
    py(ROOT/"robustness","paired robustness replay","replay.py")
    py(ROOT/"evidence","intraday evidence demo with pinned commitment",
       "example.py","--verify","demo.json","--expected-sha256",DEMO_PIN)
    with tempfile.TemporaryDirectory(prefix="spe-1.1-") as folder:
        temp=Path(folder)
        results=temp/"results"
        py(ROOT,"frozen rules on historical and held-out cases","evaluate.py","--out",results)
        py(ROOT,"score archived masked reading","reader/score.py","--out",results/"reader_metrics.json",
           "--decisions",results/"decisions.csv")
        py(ROOT,"frozen learned models and decision traces","compare_models.py","--out",results)
        for name in ("metrics.json","predictions.jsonl","reader_metrics.json","decisions.csv",
                     "learned_metrics.json","learned_traces.jsonl"):
            compare(results/name,ROOT/"results"/name)
        py(ROOT/"costs","two declared cost policies","costs.py","--out",temp/"scenarios.json")
        compare(temp/"scenarios.json",ROOT/"costs/scenarios.json")
        py(ROOT/"evidence","regenerate full evidence dossier","example.py","--out",temp/"demo.json")
        compare(temp/"demo.json",ROOT/"evidence/demo.json")
        run_dir=temp/"interventions"
        py(ROOT/"interventions","360 fresh local subprocess calls","study.py","run","--out",run_dir)
        py(ROOT/"interventions","paired outcome recount and capture checks","study.py","verify","--out",run_dir)
        for name in ("metrics.json","pairs.json","captures.jsonl"):
            compare(run_dir/name,ROOT/"interventions/results"/name)
        regenerated_zip=temp/"deposit.zip"
        py(ROOT/"deposit","regenerate deposit package","prepare.py","--out",regenerated_zip)
        py(ROOT/"deposit","verify both regenerated deposit manuscripts","verify.py",regenerated_zip,"--edition-dir",ROOT)
        with zipfile.ZipFile(regenerated_zip) as fresh, zipfile.ZipFile(ROOT/"deposit/zenodo-deposit-1.1.zip") as published:
            if sorted(fresh.namelist())!=sorted(published.namelist()) or any(fresh.read(n)!=published.read(n) for n in fresh.namelist()):
                raise ValueError("regenerated deposit content differs from publication")
        replay_site(temp)
        node=shutil.which("node")
        if node:
            command([node,"verify.js"],ROOT/"explore","offline explorer interactions in Node.js",verbose=True)
        else:
            print("SKIP  Node.js unavailable; browser-interface harnesses were not run.")
        if retrain:
            model=temp/"model"
            py(ROOT/"local_model","refit neural weights with NumPy","train.py","--output",model)
            for name in ("weights.json","training_report.json"):
                compare(model/name,ROOT/"local_model"/name)
        else:
            print("INFO  Frozen neural inference checked. Use --retrain for the reference NumPy refit.")
    print("Scientific replay complete. Archived AI-reader responses are rescored. No new human sessions are created.")


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest-sha256",help="independently retained SHA-256 of SHA256.json")
    parser.add_argument("--retrain",action="store_true",help="also refit weights and compare bytes; requires reference NumPy stack")
    parser.add_argument("--record-manifest",action="store_true",help="maintainer only: index a clean staged edition before publication")
    args=parser.parse_args()
    if sys.version_info < (3,10): parser.exit(1,"Python 3.10 or newer is required.\n")
    try:
        if args.record_manifest:
            if args.retrain or args.manifest_sha256: parser.error("manifest creation cannot be combined with verification")
            record_manifest()
            return
        verify_manifest(args.manifest_sha256)
        verify_study(args.retrain)
    except (ValueError,OSError,KeyError,zipfile.BadZipFile) as exc:
        parser.exit(1,f"Verification failed: {exc}\n")


if __name__=="__main__":
    main()
